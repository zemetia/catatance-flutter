/// Fast O(1) map indexed by uppercase ISO 4217 currency code.
final Map<String, Currency> _currencyMapByCode = {
  for (final c in currencies) c.code: c,
};

/// Public map of all currencies indexed by uppercase 3-letter currency code.
final Map<String, Currency> currencyMapByCode =
    Map.unmodifiable(_currencyMapByCode);

/// Search currencies matching code, name, or symbol.
List<Currency> searchCurrencies(String query) {
  final clean = query.trim().toLowerCase();
  if (clean.isEmpty) return currencies;

  return currencies.where((c) {
    return c.code.toLowerCase().contains(clean) ||
        c.symbol.toLowerCase().contains(clean) ||
        c.name.toLowerCase().contains(clean) ||
        c.nameId.toLowerCase().contains(clean) ||
        c.countryCode.toLowerCase().contains(clean);
  }).toList();
}
