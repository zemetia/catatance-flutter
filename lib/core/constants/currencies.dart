/// Data model and comprehensive ISO 4217 list of world currencies
/// with flag icon (emoji & country code), currency code (e.g. IDR),
/// and symbol (e.g. Rp).
class Currency {
  /// ISO 4217 3-letter currency code, e.g. "IDR", "USD".
  final String code;

  /// Currency symbol, e.g. "Rp", "$", "€", "¥".
  final String symbol;

  /// Native currency symbol, e.g. "Rp", "$", "€", "¥", "د.إ".
  final String symbolNative;

  /// English currency name, e.g. "Indonesian Rupiah".
  final String name;

  /// Indonesian currency name, e.g. "Rupiah Indonesia".
  final String nameId;

  /// Flag emoji, e.g. "🇮🇩", "🇺🇸", "🇪🇺".
  final String flag;

  /// ISO 3166-1 alpha-2 country code representing the primary country/region,
  /// e.g. "ID", "US", "EU", "GB". Useful for SVG / PNG flag image lookups.
  final String countryCode;

  /// Number of decimal digits used in standard formatting.
  /// (e.g. 0 for IDR, JPY; 2 for USD, EUR; 3 for KWD, BHD).
  final int decimalDigits;

  const Currency({
    required this.code,
    required this.symbol,
    required this.symbolNative,
    required this.name,
    required this.nameId,
    required this.flag,
    required this.countryCode,
    this.decimalDigits = 2,
  });

  /// Factory from Map / JSON.
  factory Currency.fromJson(Map<String, dynamic> json) {
    return Currency(
      code: json['code'] as String,
      symbol: json['symbol'] as String,
      symbolNative: (json['symbolNative'] ?? json['symbol']) as String,
      name: json['name'] as String,
      nameId: (json['nameId'] ?? json['name']) as String,
      flag: json['flag'] as String,
      countryCode: json['countryCode'] as String,
      decimalDigits: (json['decimalDigits'] as num?)?.toInt() ?? 2,
    );
  }

  /// Converts this currency object to a JSON-compatible Map.
  Map<String, dynamic> toJson() {
    return {
      'code': code,
      'symbol': symbol,
      'symbolNative': symbolNative,
      'name': name,
      'nameId': nameId,
      'flag': flag,
      'countryCode': countryCode,
      'decimalDigits': decimalDigits,
    };
  }

  /// Look up a currency by ISO code (case-insensitive).
  /// Throws [ArgumentError] if the code is not recognized.
  factory Currency.fromCode(String code) {
    final found = maybeFromCode(code);
    if (found == null) {
      throw ArgumentError('Unrecognized currency code: $code');
    }
    return found;
  }

  /// Look up a currency by ISO code (case-insensitive), or null if not found.
  static Currency? maybeFromCode(String? code) {
    if (code == null || code.trim().isEmpty) return null;
    return _currencyMapByCode[code.trim().toUpperCase()];
  }

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is Currency &&
          runtimeType == other.runtimeType &&
          code == other.code;

  @override
  int get hashCode => code.hashCode;

  @override
  String toString() => '$flag $code ($symbol) - $name';
}

